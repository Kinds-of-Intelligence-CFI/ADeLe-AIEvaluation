"""Rebuild the results index (RESULTS.md) and the run registry (runs.csv) of experiments/benchmarks.

Both are generated from committed files only, so never edit them by hand:
  - each study's RESULTS.md, from its **Question.**, **Answer.** and **Status.** paragraphs
    (the fixed layout in README.md);
  - each run's labels/<run>/run.json, with labels_long.csv when the run has labels.

    python experiments/benchmarks/report.py
"""

import json
import re
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent


def paragraphs(md: str) -> dict[str, str]:
    """The bold-labelled paragraphs of a RESULTS.md, keyed by label, lines joined."""
    out = {}
    for block in md.split("\n\n"):
        m = re.match(r"\*\*(\w+)\.\*\* (.*)", " ".join(block.split("\n")), re.S)
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def first_sentence(text: str) -> str:
    return re.split(r"(?<=\.)\s", text, maxsplit=1)[0]


def index() -> str:
    rows = []
    for res in sorted(HERE.glob("*/RESULTS.md")):
        p = paragraphs(res.read_text(encoding="utf-8"))
        study = res.parent.name
        rows.append(f"| [{study}]({study}/RESULTS.md) | {p['Question']} | {first_sentence(p['Answer'])} "
                    f"| {p['Status']} |")
    return "\n".join([
        "# Results",
        "",
        "Generated by `report.py` from each study's `RESULTS.md`; do not edit by hand. One row per",
        "pinned run, with its judges and label counts, is in `runs.csv`. The per-task results of every",
        "benchmark, under one set of rules, are in `panel/` (coverage: `panel/COVERAGE.md`).",
        "",
        "| study | question | answer, first sentence | status |",
        "|---|---|---|---|",
        *rows,
        "",
    ])


def registry() -> pd.DataFrame:
    rows = []
    for spec in sorted(HERE.glob("*/labels/*/run.json")):
        run = json.loads(spec.read_text())
        labels = spec.parent / "labels_long.csv"
        lab = pd.read_csv(labels) if labels.exists() else None
        rows.append({
            "study": spec.parents[2].name,
            "run": run["run_id"],
            "pinned_at": run["created_at"],
            "pinned_commit": run["repo_commit"][:7],
            "prompts": run["design"]["n_prompts"],
            "judges": ";".join(run["design"]["judges"]),
            "labels": 0 if lab is None else len(lab),
            "parsed": 0 if lab is None else int(lab["valid"].sum()),
        })
    return pd.DataFrame(rows)


def main() -> None:
    (HERE / "RESULTS.md").write_text(index(), encoding="utf-8")
    runs = registry()
    runs.to_csv(HERE / "runs.csv", index=False)
    print(f"RESULTS.md: {len(list(HERE.glob('*/RESULTS.md')))} studies; runs.csv: {len(runs)} runs")


if __name__ == "__main__":
    main()
